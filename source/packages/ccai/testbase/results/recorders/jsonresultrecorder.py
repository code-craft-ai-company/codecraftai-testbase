class JsonResultEncoder(json.JSONEncoder):
    """
        JSON encoder that serializes datetime objects as ISO formatted strings.

        This encoder extends :class:`json.JSONEncoder` to handle datetime objects,
        which are not natively serializable by the standard JSON encoder. All
        datetime objects are converted to ISO 8601 format strings.

        Usage::

            import json
            from datetime import datetime

            data = {"timestamp": datetime.now(), "value": 42}
            json_str = json.dumps(data, cls=JsonResultEncoder)
            # Output: {"timestamp": "2025-02-20T10:30:00.123456", "value": 42}

        See Also:
            :class:`SummaryJsonEncoder` in progressconcentratorservice.py for a
            similar encoder used in progress forwarding.
    """

    def default(self, obj) -> Any:
        """
            Converts non-serializable objects to JSON-compatible representations.

            This method overrides the base :class:`json.JSONEncoder.default` method
            to provide custom serialization for datetime objects. All other object
            types are delegated to the parent class implementation.

            :param obj: The object to serialize to a JSON-compatible format.

            :returns: An ISO 8601 formatted string if obj is a datetime, otherwise
                      delegates to the parent class default method.

            :raises: TypeError if the object is not serializable and the parent
                     class cannot handle it.
        """

        cval = None

        if isinstance(obj, datetime):
            cval = obj.isoformat()
        else:
            cval = json.JSONEncoder.default(self, obj)

        return cval




class JsonResultRecorder(ResultRecorder):
    """
        Records test results in JSON format.

        The :class:`JsonResultRecorder` is a concrete implementation of
        :class:`ResultRecorder` that writes test results to JSON files. It produces
        three main output files:

        1. **Summary File** (testsummary.json): Contains run metadata, timing, and
           result counts. Updated during initialization and finalization.

        2. **Stream Results File** (testresults_stream.jsos): Contains individual
           result records in JSOS (JSON Separated Object Stream) format. Records
           are written as tests execute, enabling real-time monitoring.

        3. **Consolidated Results File** (testresults.json): Contains the complete
           result tree in a single JSON document. Generated by consolidate_results()
           after the test run completes.

        Context Manager Lifecycle
        -------------------------
        The JsonResultRecorder inherits the context manager pattern from ResultRecorder:

        1. **Entry (__enter__)**: Initializes output environment, writes initial
           summary, opens stream file
        2. **Active Recording**: preview() and record() write to stream file
        3. **Exit (__exit__)**: Finalizes counts, writes final summary, closes files

        Thread Safety
        -------------
        The JsonResultRecorder is thread-safe for concurrent recording:

        - The record() method uses locking when updating result counters
        - Multiple threads can call record() concurrently without data corruption
        - The stream file writes are serialized through the lock

        JSOS Format
        -----------
        The stream results file uses JSOS (JSON Separated Object Stream) format,
        where each JSON object is preceded by an ASCII record separator character.
        This format allows efficient streaming and parsing of large result files.

        Usage Example
        -------------
        Basic usage::

            from datetime import datetime
            from ccai.testbase.results.recorders.jsonresultrecorder import JsonResultRecorder
            from ccai.testbase.results.model.renderinfo import RenderInfo
            from ccai.testbase.results.model.buildinfo import BuildInfo
            from ccai.testbase.results.model.pipelineinfo import PipelineInfo
            from ccai.testbase.results.model.jobinfo import JobInfo

            # Configure output paths
            render_info = RenderInfo(
                title="Integration Tests",
                summary_filename="/output/testsummary.json",
                summary_template="/templates/testsummary.html",
                stream_results_filename="/output/testresults_stream.jsos",
                consolidated_results_filename="/output/testresults.json",
                static_resource_source="/templates/static",
                static_resource_destination="/output/static"
            )

            # Configure metadata
            build_info = BuildInfo(branch="main", build="456", flavor="debug",
                                   release="2.0.0", url="https://builds.example.com/456")
            pipeline_info = PipelineInfo(id="pipe-2", name="Nightly", instance="run-789")
            job_info = JobInfo(id="job-2", name="Integration", type="integration")

            # Record test results
            with JsonResultRecorder(
                runid="run-uuid-456",
                start=datetime.now(),
                render_info=render_info,
                build_info=build_info,
                pipeline_info=pipeline_info,
                job_info=job_info
            ) as recorder:
                for test in tests:
                    # Write preview before test runs
                    recorder.preview(test.result)

                    # Execute test
                    test.run()

                    # Write final result after test completes
                    recorder.record(test.result)

            # After context exits:
            # - testsummary.json contains final summary
            # - testresults_stream.jsos contains all result records
            # - Call recorder.consolidate_results() to generate testresults.json

        See Also
        --------
        :class:`ResultRecorder` : Base class with full lifecycle documentation
        :class:`JsonResultEncoder` : Custom JSON encoder for datetime serialization
    """

    def __init__(self, *, runid: str, start: datetime, render_info: RenderInfo,
                 apod: Optional[str] = None, build_info: Optional[BuildInfo] = None,
                 pipeline_info: Optional[PipelineInfo] = None, job_info: Optional[JobInfo] = None):
        """
            Initializes the :class:`JsonResultRecorder` for recording test results.

            This constructor delegates to the parent :class:`ResultRecorder` constructor
            to initialize all common state. The JsonResultRecorder does not add any
            additional instance attributes.

            :param runid: The uuid string that identifies a set of test results. This ID
                          is included in the summary and can be used to correlate results
                          across systems.
            :param start: The date and time of the start of the test run. Serialized as
                          ISO 8601 format in JSON output.
            :param render_info: A :class:`RenderInfo` instance containing output file paths.
                                The summary_filename, stream_results_filename, and
                                consolidated_results_filename determine where JSON files
                                are written.
            :param apod: Optional name of an automation pod. Included in the summary JSON.
            :param build_info: Optional :class:`BuildInfo` instance. Serialized as a nested
                               object in the summary JSON.
            :param pipeline_info: Optional :class:`PipelineInfo` instance. Serialized as a
                                  nested object in the summary JSON.
            :param job_info: Optional :class:`JobInfo` instance. Serialized as a nested
                             object in the summary JSON.

            :returns: None
        """
        super(JsonResultRecorder, self).__init__(runid=runid, start=start, render_info=render_info, apod=apod,
                                                 build_info=build_info, pipeline_info=pipeline_info, job_info=job_info)
        return


    def preview(self, result: ResultNode):
        """
            Writes a preview of a result to the stream file in JSON format.

            This method serializes the result as a JSON preview (without detail section)
            and writes it to the stream results file. The preview is preceded by an
            ASCII record separator character (JSOS format).

            Preview records allow monitoring tools to see which tests are about to run
            before they complete. The result_code in a preview is typically UNSET.

            Output Format:
                The preview is written as a single JSON object with fields:
                - name: Test name
                - instance: Unique instance ID
                - parent: Parent container instance ID
                - rtype: Result type (e.g., "TEST")
                - result: Result code (typically "UNSET")
                - start: Start timestamp
                - stop: Empty string (not yet completed)

            Side Effects:
                - Writes to the stream results file
                - Flushes the output stream
                - Regenerates catalog files

            :param result: A :class:`ResultNode` object to preview. The result's
                           to_json(is_preview=True) method is called to generate
                           the JSON content.

            :returns: None
        """

        json_str = result.to_json(is_preview=True)

        self._rout.write(CHAR_RECORD_SEPERATOR)
        self._rout.write(json_str)
        self._rout.flush()

        self.catalog_output_directory()

        return


    def record(self, result: ResultNode):
        """
            Records a final result entry to the stream file in JSON format.

            This method serializes the complete result (with detail section) and
            writes it to the stream results file. The record is preceded by an
            ASCII record separator character (JSOS format). Result counters are
            updated based on the result type and code.

            Output Format:
                The record is written as a single JSON object with fields:
                - name: Test name
                - instance: Unique instance ID
                - parent: Parent container instance ID
                - rtype: Result type (e.g., "TEST")
                - result: Final result code (e.g., "PASSED", "FAILED")
                - start: Start timestamp
                - stop: Stop timestamp
                - detail: Object containing errors, failures, warnings

            Counter Updates (for TEST result type only):
                - PASSED: Increments pass_count
                - ERRORED: Increments error_count
                - FAILED: Increments failure_count
                - SKIPPED: Increments skip_count
                - Other: Increments unknown_count
                - All: Increments total_count

            Thread Safety:
                This method is thread-safe. Counter updates are performed within
                a lock-protected section to ensure atomic increments when multiple
                tests complete concurrently.

            Side Effects:
                - Writes to the stream results file
                - Flushes the output stream
                - Updates result counters (thread-safe)
                - Regenerates catalog files

            :param result: A :class:`ResultNode` object to record. The result's
                           to_json(is_preview=False) method is called to generate
                           the JSON content.

            :returns: None
        """
        
        json_str = result.to_json(is_preview=False)

        self._rout.write(CHAR_RECORD_SEPERATOR)
        self._rout.write(json_str)
        self._rout.flush()

        self._lock.acquire()
        try:
            if result.result_type == ResultType.TEST:
                self._total_count += 1

                result_code = result.result_code
                if result_code == ResultCode.PASSED:
                    self._pass_count += 1
                elif result_code == ResultCode.ERRORED:
                    self._error_count += 1
                elif result_code == ResultCode.FAILED:
                    self._failure_count += 1
                elif result_code == ResultCode.SKIPPED:
                    self._skip_count += 1
                else:
                    self._unknown_count += 1
        finally:
            self._lock.release()

        self.catalog_output_directory()

        return


    def update_summary(self):
        """
            Writes the current summary state to the summary JSON file.

            This method serializes the internal summary dictionary to JSON and
            writes it to the configured summary_filename. The output is formatted
            with 4-space indentation for readability.

            The :class:`JsonResultEncoder` is used to handle datetime serialization,
            converting datetime objects to ISO 8601 format strings.

            Output Format:
                The summary is written as a JSON object with fields:
                - version: Summary format version
                - title: Test run title
                - runid: Unique run identifier
                - build: Build metadata object
                - pipeline: Pipeline metadata object
                - job: Job metadata object
                - start: Start timestamp (ISO 8601)
                - stop: Stop timestamp (ISO 8601) or null
                - result: Current status ("RUNNING", "PASSED", "FAILED")
                - apod: Automation pod identifier
                - totals: Reserved for future use
                - running: Dictionary of currently running tasks
                - detail: Final counts (only after finalization)

            Side Effects:
                - Writes to the summary file (overwrites existing content)
                - Regenerates catalog files

            :returns: None

            :raises: ResultRecordingError if the summary file cannot be written.
                     The error includes the file path, operation description,
                     and underlying exception details.
        """

        summary_filename = self._render_info.summary_filename
        try:
            with open(summary_filename, 'w') as sout:
                json.dump(self._summary, sout, indent=4, cls=JsonResultEncoder)
        except OSError as err:
            errmsg = f"Failed to write summary to '{summary_filename}'."
            raise ResultRecordingError(
                errmsg,
                file_path=summary_filename,
                operation="writing summary JSON",
                original_error=err
            ) from err

        self.catalog_output_directory()

        return


    def write_consolidated_results(self, root_node: dict):
        """
            Writes the consolidated results tree to the consolidated results JSON file.

            This method serializes the complete result tree (built by consolidate_results())
            to JSON and writes it to the configured consolidated_results_filename. The
            output is formatted with 4-space indentation for readability.

            The :class:`JsonResultEncoder` is used to handle datetime serialization,
            converting datetime objects to ISO 8601 format strings.

            Output Format:
                The consolidated results are written as a hierarchical JSON structure::

                    {
                        "name": "Job Name",
                        "instance": "job-uuid",
                        "parent": null,
                        "rtype": "JOB",
                        "items": [
                            {
                                "name": "module.name",
                                "instance": "container-uuid",
                                "parent": "job-uuid",
                                "rtype": "TEST_CONTAINER",
                                "items": [
                                    {
                                        "name": "test_function",
                                        "instance": "test-uuid",
                                        "result": "PASSED",
                                        "tasking_groups": [...]
                                    }
                                ]
                            }
                        ]
                    }

            Side Effects:
                - Writes to the consolidated results file (overwrites existing content)
                - Regenerates catalog files

            :param root_node: A dictionary representing the root of the consolidated
                              result tree. This is typically a JobContainer with nested
                              TestContainers, TestResults, TaskingGroups, and TaskingResults.

            :returns: None

            :raises: ResultRecordingError if the consolidated results file cannot be written.
                     The error includes the file path, operation description,
                     and underlying exception details.
        """

        consolidated_filename = self._render_info.consolidated_results_filename
        try:
            with open(consolidated_filename, 'w+') as rout:
                json.dump(root_node, rout, indent=4, cls=JsonResultEncoder)
        except OSError as err:
            errmsg = f"Failed to write consolidated results to '{consolidated_filename}'."
            raise ResultRecordingError(
                errmsg,
                file_path=consolidated_filename,
                operation="writing consolidated results JSON",
                original_error=err
            ) from err

        self.catalog_output_directory()

        return
